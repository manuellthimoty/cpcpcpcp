void solve(){
    ll n, k ; cin >> n >> k;
    ll up_bound = n/k + 1;
    ll m = log2(up_bound);
    ll R = n - (k * ((1LL << m) -1));
    ll ans = k * m + R/(1LL << m);

    cout << ans << endl;

}
